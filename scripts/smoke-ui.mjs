import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1480,height:1080}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
  await page.goto(process.env.SMOKE_URL||'http://127.0.0.1:5173');
  await page.getByText('Modell · keine Messung',{exact:false}).waitFor();
  assert.equal(await page.locator('canvas').count(),1);
  const width=page.getByRole('spinbutton',{name:'Breite X / m',exact:true});
  await width.fill('5');await width.press('Tab');
  await page.getByText('ungespeichert',{exact:false}).waitFor();
  await width.fill('0');await width.press('Tab');
  await page.getByRole('status').filter({hasText:'Raumabmessung'}).waitFor();
  assert.equal(await width.inputValue(),'5');
  await page.getByRole('button',{name:'Hinweis schließen'}).click();
  await page.getByRole('button',{name:/Akustikanalyse/}).click();
  await page.getByRole('heading',{name:'Reflexionspfade & SBIR'}).waitFor();
  assert.ok(await page.locator('tr.early').count()>0);
  await page.getByRole('checkbox',{name:'Modales Druckfeld'}).check();
  await page.getByRole('button',{name:'Animation abspielen'}).click();
  await page.waitForTimeout(200);
  await page.getByRole('button',{name:'Animation pausieren'}).click();
  await page.screenshot({path:'/workspace/Raumakustik/docs/oberflaeche.png',fullPage:true});
  await page.getByRole('button',{name:/REW-Messungen/}).click();
  await page.locator('input[accept=".txt,.csv,.wav"]').setInputFiles({name:'REW-L.txt',mimeType:'text/plain',buffer:Buffer.from('* REW frequency\n20 75 -10\n40 80 -20\n80 78 -40\n160 79 -50')});
  await page.getByRole('heading',{name:'REW-L.txt',exact:true}).waitFor();
  assert.ok(await page.getByText('Frequenzgang',{exact:true}).count()>0);
  await page.getByLabel('Lautsprecher',{exact:true}).selectOption('L');
  await page.getByLabel('Mikrofonposition',{exact:true}).selectOption('M1');
  await page.getByRole('checkbox',{name:'Timing-Referenz',exact:true}).check();
  await page.getByRole('checkbox',{name:'Mikrofonkalibrierung',exact:true}).check();
  const ir=Array.from({length:2400},(_,i)=>`${i/8000} ${i===0?1:i===40?0.5:Math.exp(-i/8000*12)*0.001}`).join('\n');
  await page.getByLabel('Textdatei enthält').selectOption('impulse');
  await page.locator('input[accept=".txt,.csv,.wav"]').setInputFiles({name:'REW-IR.txt',mimeType:'text/plain',buffer:Buffer.from(ir)});
  await page.getByRole('heading',{name:'REW-IR.txt',exact:true}).waitFor();
  await page.getByLabel('Lautsprecher',{exact:true}).selectOption('L');
  await page.getByLabel('Mikrofonposition',{exact:true}).selectOption('M1');
  await page.getByText('5.00 ms',{exact:true}).waitFor();
  const [saved]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Projekt speichern',exact:true}).click()]);
  const path=await saved.path(),project=JSON.parse(await fs.readFile(path,'utf8'));
  assert.equal(project.room.dimensions[0],5);assert.equal(project.measurements.length,2);assert.equal(project.measurements[0].metadata.timingReference,true);
  await page.getByRole('button',{name:/KI & Updates/}).click();
  assert.equal(await page.getByRole('button',{name:'Bericht kopieren & ChatGPT öffnen'}).isDisabled(),true);
  assert.equal(await page.getByRole('button',{name:'Bericht an OpenAI senden'}).isDisabled(),true);
  const [report]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Aktuellen Bericht exportieren'}).click()]);
  const r=JSON.parse(await fs.readFile(await report.path(),'utf8'));assert.equal(r.measured.length,2);assert.ok(r.calculated.paths.length>6);
  assert.deepEqual(errors,[]);console.log('UI-Smoke erfolgreich: 3D, Raumeingaben, Fehlergrenzen, Moden, Animation, FR/IR-Import, Messzuordnung, Projektspeicherung, Berichtexport. Keine JavaScript-Fehler.');
}finally{await browser.close();}
